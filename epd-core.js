/*
 * epd-core.js — image pipeline for the Waveshare ESP32-S3-ePaper-1.54G (200x200, 4 colors).
 *
 * Output format (from vendor epaper_port.h / GUI_Paint.c, repo waveshareteam/ESP32-S3-ePaper-1.54G):
 *   color index: black 0, white 1, yellow 2, red 3
 *   2 bits per pixel, 4 pixels per byte, leftmost pixel in bits 7..6, rows top to bottom
 *   200x200 -> 50 bytes per row -> 10000 bytes, sent after command 0x10
 *
 * No DOM access here, so the same file runs in the tool page and in test/test.html.
 */
(function (root) {
  'use strict';

  const INDEX = Object.freeze({ black: 0, white: 1, yellow: 2, red: 3 });
  const NAMES = ['black', 'white', 'yellow', 'red'];

  // Pure RGB per index. BMP export always uses these so the vendor reader thresholds (127/128) classify them.
  const PURE_RGB = Object.freeze([[0, 0, 0], [255, 255, 255], [255, 255, 0], [255, 0, 0]]);

  // [ASSUMED] Rough look of a real 4-color panel; not measured on this board. Only used for preview/matching.
  const PANEL_RGB_GUESS = Object.freeze([[38, 34, 36], [226, 224, 214], [228, 190, 30], [178, 38, 40]]);

  function bufferSize(w, h) { return Math.ceil(w / 4) * h; }

  function pack2bpp(idx, w, h) {
    const wb = Math.ceil(w / 4);
    const out = new Uint8Array(wb * h);
    for (let y = 0; y < h; y++) {
      for (let xb = 0; xb < wb; xb++) {
        let byte = 0;
        for (let k = 0; k < 4; k++) {
          const x = xb * 4 + k;
          // Pad the tail of a row with white, matching vendor Paint_Clear(WHITE) before drawing.
          const v = x < w ? (idx[y * w + x] & 3) : INDEX.white;
          byte |= v << (6 - 2 * k);
        }
        out[y * wb + xb] = byte;
      }
    }
    return out;
  }

  function unpack2bpp(bytes, w, h) {
    const wb = Math.ceil(w / 4);
    const out = new Uint8Array(w * h);
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < w; x++) {
        out[y * w + x] = (bytes[y * wb + (x >> 2)] >> (6 - 2 * (x & 3))) & 3;
      }
    }
    return out;
  }

  // 24-bit bottom-up BMP, the format vendor GUI_ReadBmp_RGB_4Color reads from the SD card.
  function toBMP24(idx, w, h) {
    const row = w * 3;
    const pad = (4 - (row % 4)) % 4;
    const dataSize = (row + pad) * h;
    const buf = new Uint8Array(54 + dataSize);
    const dv = new DataView(buf.buffer);
    buf[0] = 0x42; buf[1] = 0x4D;
    dv.setUint32(2, 54 + dataSize, true);
    dv.setUint32(10, 54, true);
    dv.setUint32(14, 40, true);
    dv.setInt32(18, w, true);
    dv.setInt32(22, h, true);
    dv.setUint16(26, 1, true);
    dv.setUint16(28, 24, true);
    dv.setUint32(30, 0, true);
    dv.setUint32(34, dataSize, true);
    dv.setInt32(38, 2835, true);
    dv.setInt32(42, 2835, true);
    let p = 54;
    for (let y = h - 1; y >= 0; y--) {
      for (let x = 0; x < w; x++) {
        const c = PURE_RGB[idx[y * w + x] & 3];
        buf[p++] = c[2]; buf[p++] = c[1]; buf[p++] = c[0];
      }
      p += pad;
    }
    return buf;
  }

  function toCArray(bytes, name, w, h) {
    const id = String(name || 'epd_image').replace(/[^A-Za-z0-9_]/g, '_').replace(/^([0-9])/, '_$1');
    const lines = [];
    lines.push('// Generated by epd-image tool for ESP32-S3-ePaper-1.54G');
    if (w && h) lines.push(`// ${w} x ${h} px, 2 bpp, index: black 0, white 1, yellow 2, red 3, MSB = leftmost pixel`);
    lines.push('#include <stdint.h>');
    lines.push('');
    lines.push(`const uint8_t ${id}[${bytes.length}] = {`);
    for (let i = 0; i < bytes.length; i += 16) {
      const chunk = Array.from(bytes.subarray(i, i + 16), b => '0x' + b.toString(16).toUpperCase().padStart(2, '0'));
      lines.push('    ' + chunk.join(', ') + (i + 16 < bytes.length ? ',' : ''));
    }
    lines.push('};');
    lines.push('');
    return lines.join('\n');
  }

  function indicesToRGBA(idx, w, h, palette) {
    const pal = palette || PURE_RGB;
    const out = new Uint8ClampedArray(w * h * 4);
    for (let i = 0; i < w * h; i++) {
      const c = pal[idx[i] & 3];
      out[i * 4] = c[0]; out[i * 4 + 1] = c[1]; out[i * 4 + 2] = c[2]; out[i * 4 + 3] = 255;
    }
    return out;
  }

  function rotateIndices(idx, w, h, deg) {
    const d = ((deg % 360) + 360) % 360;
    if (d === 0) return Uint8Array.from(idx);
    const out = new Uint8Array(w * h);
    if (d === 180) {
      for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) out[y * w + x] = idx[(h - 1 - y) * w + (w - 1 - x)];
      return out;
    }
    // 90 / 270: the result is h wide and w tall.
    const nw = h, nh = w;
    for (let y = 0; y < nh; y++) {
      for (let x = 0; x < nw; x++) {
        const sx = d === 90 ? y : w - 1 - y;
        const sy = d === 90 ? h - 1 - x : x;
        out[y * nw + x] = idx[sy * w + sx];
      }
    }
    return out;
  }

  // brightness, contrast, saturation in -100..100; gamma > 0 (1 = neutral).
  function adjust(rgba, o) {
    const b = (o && o.brightness || 0) * 2.55;
    const c = (o && o.contrast || 0) * 2.55;
    const s = 1 + (o && o.saturation || 0) / 100;
    const g = o && o.gamma > 0 ? o.gamma : 1;
    const cf = (259 * (c + 255)) / (255 * (259 - c));
    const out = new Uint8ClampedArray(rgba.length);
    const lut = new Float32Array(256);
    for (let v = 0; v < 256; v++) lut[v] = g === 1 ? v : 255 * Math.pow(v / 255, 1 / g);
    for (let i = 0; i < rgba.length; i += 4) {
      let r = lut[rgba[i]], gg = lut[rgba[i + 1]], bb = lut[rgba[i + 2]];
      if (s !== 1) {
        const l = 0.299 * r + 0.587 * gg + 0.114 * bb;
        r = l + (r - l) * s; gg = l + (gg - l) * s; bb = l + (bb - l) * s;
      }
      if (c !== 0) { r = (r - 128) * cf + 128; gg = (gg - 128) * cf + 128; bb = (bb - 128) * cf + 128; }
      out[i] = r + b; out[i + 1] = gg + b; out[i + 2] = bb + b; out[i + 3] = rgba[i + 3];
    }
    return out;
  }

  function srgbToLab(r, g, b) {
    function lin(v) { v /= 255; return v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); }
    const R = lin(r), G = lin(g), B = lin(b);
    let X = (R * 0.4124 + G * 0.3576 + B * 0.1805) / 0.95047;
    let Y = (R * 0.2126 + G * 0.7152 + B * 0.0722);
    let Z = (R * 0.0193 + G * 0.1192 + B * 0.9505) / 1.08883;
    function f(t) { return t > 0.008856 ? Math.cbrt(t) : 7.787 * t + 16 / 116; }
    X = f(X); Y = f(Y); Z = f(Z);
    return [116 * Y - 16, 500 * (X - Y), 200 * (Y - Z)];
  }

  function makeMatcher(palette, metric) {
    const pal = palette.map(c => [c[0], c[1], c[2]]);
    if (metric === 'lab') {
      const labs = pal.map(c => srgbToLab(c[0], c[1], c[2]));
      return function (r, g, b) {
        const L = srgbToLab(r, g, b);
        let best = 0, bd = Infinity;
        for (let i = 0; i < labs.length; i++) {
          const d0 = L[0] - labs[i][0], d1 = L[1] - labs[i][1], d2 = L[2] - labs[i][2];
          const d = d0 * d0 + d1 * d1 + d2 * d2;
          if (d < bd) { bd = d; best = i; }
        }
        return best;
      };
    }
    if (metric === 'redmean') {
      return function (r, g, b) {
        let best = 0, bd = Infinity;
        for (let i = 0; i < pal.length; i++) {
          const rm = (r + pal[i][0]) / 2;
          const dr = r - pal[i][0], dg = g - pal[i][1], db = b - pal[i][2];
          const d = (2 + rm / 256) * dr * dr + 4 * dg * dg + (2 + (255 - rm) / 256) * db * db;
          if (d < bd) { bd = d; best = i; }
        }
        return best;
      };
    }
    return function (r, g, b) {
      let best = 0, bd = Infinity;
      for (let i = 0; i < pal.length; i++) {
        const dr = r - pal[i][0], dg = g - pal[i][1], db = b - pal[i][2];
        const d = dr * dr + dg * dg + db * db;
        if (d < bd) { bd = d; best = i; }
      }
      return best;
    };
  }

  const KERNELS = {
    floyd: [[1, 0, 7 / 16], [-1, 1, 3 / 16], [0, 1, 5 / 16], [1, 1, 1 / 16]],
    atkinson: [[1, 0, 1 / 8], [2, 0, 1 / 8], [-1, 1, 1 / 8], [0, 1, 1 / 8], [1, 1, 1 / 8], [0, 2, 1 / 8]]
  };

  function bayer(n) {
    let m = [[0]];
    while (m.length < n) {
      const s = m.length, nm = [];
      for (let y = 0; y < 2 * s; y++) {
        nm.push([]);
        for (let x = 0; x < 2 * s; x++) {
          const q = (y < s ? 0 : 2) + (x < s ? 0 : 1);
          nm[y].push(4 * m[y % s][x % s] + [0, 2, 3, 1][q]);
        }
      }
      m = nm;
    }
    const nn = n * n;
    return m.map(row => row.map(v => (v + 0.5) / nn - 0.5));
  }

  // Map RGBA pixels to palette indices 0..3.
  // opts: palette (4 RGB, position = color index), metric 'rgb'|'redmean'|'lab',
  //       dither 'none'|'floyd'|'atkinson'|'bayer4'|'bayer8', strength 0..1, serpentine bool
  function quantize(rgba, w, h, opts) {
    const o = opts || {};
    const palette = o.palette || PURE_RGB;
    const match = makeMatcher(palette, o.metric || 'rgb');
    const dither = o.dither || 'floyd';
    const strength = o.strength == null ? 1 : o.strength;
    const out = new Uint8Array(w * h);

    if (dither === 'bayer4' || dither === 'bayer8') {
      const m = bayer(dither === 'bayer4' ? 4 : 8), n = m.length;
      const spread = 96 * strength;
      for (let y = 0; y < h; y++) {
        for (let x = 0; x < w; x++) {
          const i = (y * w + x) * 4, t = m[y % n][x % n] * spread;
          out[y * w + x] = match(clamp(rgba[i] + t), clamp(rgba[i + 1] + t), clamp(rgba[i + 2] + t));
        }
      }
      return out;
    }

    const kernel = KERNELS[dither];
    if (!kernel) {
      for (let p = 0; p < w * h; p++) out[p] = match(rgba[p * 4], rgba[p * 4 + 1], rgba[p * 4 + 2]);
      return out;
    }

    const buf = new Float32Array(w * h * 3);
    for (let p = 0; p < w * h; p++) {
      buf[p * 3] = rgba[p * 4]; buf[p * 3 + 1] = rgba[p * 4 + 1]; buf[p * 3 + 2] = rgba[p * 4 + 2];
    }
    const serp = !!o.serpentine;
    for (let y = 0; y < h; y++) {
      const rev = serp && (y & 1);
      for (let k = 0; k < w; k++) {
        const x = rev ? w - 1 - k : k;
        const p = y * w + x;
        const r = clamp(buf[p * 3]), g = clamp(buf[p * 3 + 1]), b = clamp(buf[p * 3 + 2]);
        const ci = match(r, g, b);
        out[p] = ci;
        const c = palette[ci];
        const er = (r - c[0]) * strength, eg = (g - c[1]) * strength, eb = (b - c[2]) * strength;
        for (let j = 0; j < kernel.length; j++) {
          const nx = x + (rev ? -kernel[j][0] : kernel[j][0]), ny = y + kernel[j][1];
          if (nx < 0 || nx >= w || ny >= h) continue;
          const q = (ny * w + nx) * 3, f = kernel[j][2];
          buf[q] += er * f; buf[q + 1] += eg * f; buf[q + 2] += eb * f;
        }
      }
    }
    return out;
  }

  function clamp(v) { return v < 0 ? 0 : v > 255 ? 255 : v; }

  let CRC_TABLE = null;
  function crc32(bytes) {
    if (!CRC_TABLE) {
      CRC_TABLE = new Uint32Array(256);
      for (let n = 0; n < 256; n++) {
        let c = n;
        for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1;
        CRC_TABLE[n] = c >>> 0;
      }
    }
    let crc = 0xFFFFFFFF;
    for (let i = 0; i < bytes.length; i++) crc = CRC_TABLE[(crc ^ bytes[i]) & 0xFF] ^ (crc >>> 8);
    return (crc ^ 0xFFFFFFFF) >>> 0;
  }

  // Minimal ZIP writer (STORE, no compression). files: [{ name, data: Uint8Array | string }].
  // Needed because artifact downloads only allow a fixed list of extensions (.zip yes, .bin/.h/.bmp no).
  function makeZip(files) {
    const enc = new TextEncoder();
    const entries = files.map(f => {
      const data = typeof f.data === 'string' ? enc.encode(f.data) : f.data;
      return { name: enc.encode(f.name), data, crc: crc32(data) };
    });
    let size = 22;
    entries.forEach(e => { size += 30 + e.name.length + e.data.length + 46 + e.name.length; });
    const out = new Uint8Array(size);
    const dv = new DataView(out.buffer);
    let p = 0;
    const DOS_TIME = 0, DOS_DATE = (1 << 5) | 1; // 1980-01-01, fixed so output is deterministic
    entries.forEach(e => {
      e.offset = p;
      dv.setUint32(p, 0x04034b50, true); dv.setUint16(p + 4, 20, true); dv.setUint16(p + 6, 0x0800, true);
      dv.setUint16(p + 8, 0, true); dv.setUint16(p + 10, DOS_TIME, true); dv.setUint16(p + 12, DOS_DATE, true);
      dv.setUint32(p + 14, e.crc, true); dv.setUint32(p + 18, e.data.length, true); dv.setUint32(p + 22, e.data.length, true);
      dv.setUint16(p + 26, e.name.length, true); dv.setUint16(p + 28, 0, true);
      out.set(e.name, p + 30); p += 30 + e.name.length;
      out.set(e.data, p); p += e.data.length;
    });
    const cdStart = p;
    entries.forEach(e => {
      dv.setUint32(p, 0x02014b50, true); dv.setUint16(p + 4, 20, true); dv.setUint16(p + 6, 20, true);
      dv.setUint16(p + 8, 0x0800, true); dv.setUint16(p + 10, 0, true); dv.setUint16(p + 12, DOS_TIME, true);
      dv.setUint16(p + 14, DOS_DATE, true); dv.setUint32(p + 16, e.crc, true);
      dv.setUint32(p + 20, e.data.length, true); dv.setUint32(p + 24, e.data.length, true);
      dv.setUint16(p + 28, e.name.length, true); dv.setUint16(p + 30, 0, true); dv.setUint16(p + 32, 0, true);
      dv.setUint16(p + 34, 0, true); dv.setUint16(p + 36, 0, true); dv.setUint32(p + 38, 0, true);
      dv.setUint32(p + 42, e.offset, true);
      out.set(e.name, p + 46); p += 46 + e.name.length;
    });
    dv.setUint32(p, 0x06054b50, true); dv.setUint16(p + 4, 0, true); dv.setUint16(p + 6, 0, true);
    dv.setUint16(p + 8, entries.length, true); dv.setUint16(p + 10, entries.length, true);
    dv.setUint32(p + 12, p - cdStart, true); dv.setUint32(p + 16, cdStart, true); dv.setUint16(p + 20, 0, true);
    return out;
  }

  // Longest base name: vendor list_scan_dir skips paths over 96 chars, so "/sdcard/bmp/" + name + ".bmp" must fit.
  const MAX_NAME = 78;

  // Check a typed file name. Only A-Z a-z 0-9 _ - survive: the firmware FATFS uses code page 437.
  function checkName(raw) {
    const s = String(raw == null ? '' : raw).normalize('NFC');
    const chars = Array.from(s);
    const spaces = chars.filter(c => /\s/.test(c)).length;
    const bad = Array.from(new Set(chars.filter(c => !/\s/.test(c) && !/^[A-Za-z0-9_-]$/.test(c))));
    return { empty: s.length === 0, spaces, bad, safe: s.replace(/[^A-Za-z0-9_-]/gu, '_') || 'epd_image' };
  }

  // Parse the sequence box. Empty = no prefix. Pads to 2 digits because the firmware sorts names with strcmp.
  function parseSeq(raw) {
    const s = String(raw == null ? '' : raw).trim();
    if (!s) return { valid: true, prefix: '', next: '', sortWarn: false };
    if (!/^\d{1,4}$/.test(s)) return { valid: false, prefix: '', next: s, sortWarn: false };
    const n = parseInt(s, 10), width = Math.max(2, s.length);
    return {
      valid: true,
      prefix: String(n).padStart(width, '0') + '_',
      next: String(n + 1).padStart(width, '0'),
      sortWarn: n >= 100 && s.length === String(n).length
    };
  }

  function exportName(rawName, rawSeq) {
    const name = checkName(rawName), seq = parseSeq(rawSeq);
    const file = seq.prefix + name.safe;
    return { name, seq, file, tooLong: file.length > MAX_NAME };
  }

  function countColors(idx) {
    const c = [0, 0, 0, 0];
    for (let i = 0; i < idx.length; i++) c[idx[i] & 3]++;
    return c;
  }

  root.EPDCore = Object.freeze({
    INDEX, NAMES, PURE_RGB, PANEL_RGB_GUESS,
    bufferSize, pack2bpp, unpack2bpp, toBMP24, toCArray, indicesToRGBA,
    rotateIndices, adjust, quantize, countColors, srgbToLab, crc32, makeZip,
    MAX_NAME, checkName, parseSeq, exportName
  });
})(typeof window !== 'undefined' ? window : globalThis);
